// Package resetgen generates Reset() methods for structs marked with the comment "// generate:reset";
// cmd/reset runs it. See cmd/reset for the rules of a generated method.
package resetgen

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"go/ast"
	"go/format"
	"go/types"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
	"text/template"
	"unicode"
	"unicode/utf8"

	"golang.org/x/tools/go/packages"

	"github.com/shigabutdinoff/go-godot-kit/internal/atomicfile"
)

const (
	marker = "generate:reset"

	genFile = "reset.gen.go"

	header = "// Code generated by go-godot-kit/cmd/reset; DO NOT EDIT.\n"
)

// Run loads the module packages in root and writes reset.gen.go into every package with marked structs,
// removing a previously generated one from the rest. It returns an error if ctx is canceled.
func Run(ctx context.Context, root string) error {
	cfg := &packages.Config{
		Context: ctx,

		Mode: packages.NeedName | packages.NeedFiles | packages.NeedSyntax | packages.NeedTypes |
			packages.NeedTypesInfo | packages.NeedImports | packages.NeedDeps,
		Dir: root,
	}
	pkgs, err := packages.Load(cfg, "./...")
	if err != nil {
		return fmt.Errorf("load packages: %w", err)
	}

	marked := map[*types.TypeName]bool{}
	for _, p := range pkgs {
		for _, n := range markedNamed(p) {
			marked[n.Obj()] = true
		}
	}
	for _, p := range pkgs {
		if err := ctx.Err(); err != nil {
			return fmt.Errorf("interrupted: %w", err)
		}
		if len(p.GoFiles) == 0 {
			continue
		}
		src, err := generate(p, marked)
		if err != nil {
			return fmt.Errorf("%s: %w", p.PkgPath, err)
		}
		out := filepath.Join(filepath.Dir(p.GoFiles[0]), genFile)
		if src == nil {
			err = removeGenerated(out)
		} else {
			err = atomicfile.Write(out, src, 0o644)
		}
		if err != nil {
			return err
		}
	}
	return nil
}

// removeGenerated removes path if it is a file generated by cmd/reset.
// It leaves a missing file or a foreign file with the same name alone and returns nil.
func removeGenerated(path string) error {
	data, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) || err == nil && !bytes.HasPrefix(data, []byte(header)) {
		return nil
	}
	if err != nil {
		return err
	}
	return os.Remove(path)
}

// markedNamed returns the named types of the marked structs in package p, or nil if the package types are not loaded.
func markedNamed(p *packages.Package) []*types.Named {
	var res []*types.Named
	if p.Types == nil {
		return nil
	}
	for _, name := range markedStructs(p.Syntax) {
		if named, ok := p.Types.Scope().Lookup(name).Type().(*types.Named); ok {
			res = append(res, named)
		}
	}
	return res
}

// generate returns the formatted reset.gen.go source for package p, or nil if it has no marked structs.
// marked holds the marked types of all module packages. Package load errors other than type errors are returned as is.
func generate(p *packages.Package, marked map[*types.TypeName]bool) ([]byte, error) {
	for _, e := range p.Errors {
		if e.Kind != packages.TypeError {
			return nil, e
		}
	}
	g := gen{pkg: p.Types, imports: map[string]string{}, marked: marked}
	f := genData{Header: header, Package: p.Name}
	named := markedNamed(p)
	if len(named) == 0 {
		return nil, nil
	}

	for _, n := range named {
		g.method(n, "_")
	}
	for _, n := range named {
		f.Methods = append(f.Methods, g.method(n, g.recv(n)))
	}
	for _, path := range slices.Sorted(maps.Keys(g.imports)) {
		f.Imports = append(f.Imports, genImport{Name: g.imports[path], Path: path})
	}
	var b bytes.Buffer
	if err := fileTmpl.Execute(&b, f); err != nil {
		return nil, fmt.Errorf("template %s: %w", genFile, err)
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format %s: %w", genFile, err)
	}
	return src, nil
}

var fileTmpl = template.Must(template.New(genFile).Parse(`{{.Header}}
package {{.Package}}
{{if .Imports}}
import (
{{- range .Imports}}
	{{.Name}} {{printf "%q" .Path}}
{{- end}}
)
{{end}}
{{- range .Methods}}
// Reset resets {{.Type}} to its initial values.
func ({{.Recv}} *{{.Type}}{{.TypeParams}}) Reset() {
	if {{.Recv}} == nil {
		return
	}
{{- range .Lines}}
{{.}}
{{- end}}
}
{{end -}}
`))

// genData is the fileTmpl data for one reset.gen.go file.
type genData struct {
	Header, Package string
	Imports         []genImport
	Methods         []genMethod
}

// genImport is an import of the generated file: Name and Path.
type genImport struct{ Name, Path string }

// genMethod is the data for one Reset method: the type, its type parameters, the receiver name and the body lines.
type genMethod struct {
	Type, TypeParams, Recv string
	Lines                  []string
}

// markedStructs returns the names of structs in files whose declaration comment contains a generate:reset line.
func markedStructs(files []*ast.File) []string {
	var names []string
	for _, f := range files {
		for _, d := range f.Decls {
			gd, ok := d.(*ast.GenDecl)
			if !ok {
				continue
			}
			for _, s := range gd.Specs {
				ts, ok := s.(*ast.TypeSpec)
				if !ok {
					continue
				}
				if _, ok := ts.Type.(*ast.StructType); !ok {
					continue
				}
				doc := ts.Doc
				if doc == nil && len(gd.Specs) == 1 {
					doc = gd.Doc
				}
				if hasMarker(doc) {
					names = append(names, ts.Name.Name)
				}
			}
		}
	}
	return names
}

// hasMarker reports whether doc contains a generate:reset line. It returns false for nil.
func hasMarker(doc *ast.CommentGroup) bool {
	if doc == nil {
		return false
	}
	for _, c := range doc.List {
		if strings.TrimSpace(strings.TrimPrefix(c.Text, "//")) == marker {
			return true
		}
	}
	return false
}

// gen builds Reset methods for package pkg. imports collects the imports of the generated code (path → name),
// marked holds the types that will get a generated Reset.
type gen struct {
	pkg     *types.Package
	imports map[string]string
	marked  map[*types.TypeName]bool
}

// method returns the Reset method of struct named with receiver recv. It skips fields named _.
func (g *gen) method(named *types.Named, recv string) genMethod {
	st := named.Underlying().(*types.Struct)
	m := genMethod{Type: named.Obj().Name(), Recv: recv}
	if tps := named.TypeParams(); tps.Len() > 0 {
		params := make([]string, tps.Len())
		for i := range tps.Len() {
			params[i] = tps.At(i).Obj().Name()
		}
		m.TypeParams = "[" + strings.Join(params, ", ") + "]"
	}
	for f := range st.Fields() {
		if f.Name() == "_" {
			continue
		}
		m.Lines = g.reset(m.Lines, m.Recv+"."+f.Name(), f.Type(), 1)
	}
	return m
}

// recv returns the receiver name for named: the first letter of the type in lower case,
// with a numeric suffix if the name is taken by a type parameter, a package declaration or an import.
func (g *gen) recv(named *types.Named) string {
	first, _ := utf8.DecodeRuneInString(named.Obj().Name())
	return unique(string(unicode.ToLower(first)), func(name string) bool {
		for tp := range named.TypeParams().TypeParams() {
			if tp.Obj().Name() == name {
				return true
			}
		}
		return g.taken(name)
	})
}

// taken reports whether name is taken by a package declaration or an import name.
func (g *gen) taken(name string) bool {
	return g.pkg.Scope().Lookup(name) != nil || slices.Contains(slices.Collect(maps.Values(g.imports)), name)
}

// unique returns base or, if taken reports it as taken, the first free one of base2, base3 and so on.
func unique(base string, taken func(string) bool) string {
	name := base
	for i := 2; taken(name); i++ {
		name = base + strconv.Itoa(i)
	}
	return name
}

// reset appends to lines code indented by depth that resets x of type t to its initial value, and returns lines.
func (g *gen) reset(lines []string, x string, t types.Type, depth int) []string {
	ind := strings.Repeat("\t", depth)
	add := func(format string, a ...any) { lines = append(lines, ind+fmt.Sprintf(format, a...)) }
	if tp, ok := t.(*types.TypeParam); ok {
		add("%s = *new(%s)", x, tp.Obj().Name())
		return lines
	}
	switch u := t.Underlying().(type) {
	case *types.Slice:
		add("%s = %s[:0]", x, paren(x))
	case *types.Map:
		add("clear(%s)", x)
	case *types.Pointer:
		add("if %s != nil {", x)
		if g.hasReset(u.Elem()) {
			add("\t%s.Reset()", paren(x))
		} else {
			lines = g.reset(lines, "*"+x, u.Elem(), depth+1)
		}
		add("}")
	default:
		if g.hasReset(t) {
			add("%s.Reset()", paren(x))
		} else {
			add("%s = %s", x, g.zero(t))
		}
	}
	return lines
}

// hasReset reports whether *t has a Reset() method with no parameters and results, including one not generated yet.
// It returns false for interfaces.
func (g *gen) hasReset(t types.Type) bool {
	if n, ok := types.Unalias(t).(*types.Named); ok && g.marked[n.Obj()] {
		return true
	}
	if _, ok := t.Underlying().(*types.Interface); ok {
		return false
	}
	obj, _, _ := types.LookupFieldOrMethod(types.NewPointer(t), true, nil, "Reset")
	fn, ok := obj.(*types.Func)
	if !ok {
		return false
	}
	sig := fn.Signature()
	return sig.Params().Len() == 0 && sig.Results().Len() == 0
}

// zero returns the zero value literal of type t.
func (g *gen) zero(t types.Type) string {
	switch u := t.Underlying().(type) {
	case *types.Basic:
		switch {
		case u.Info()&types.IsBoolean != 0:
			return "false"
		case u.Info()&types.IsString != 0:
			return `""`
		case u.Info()&types.IsNumeric != 0:
			return "0"
		}
		return "nil"
	case *types.Struct, *types.Array:
		return types.TypeString(t, g.qualify) + "{}"
	}
	return "nil"
}

// qualify returns the name of package p in the code of g.pkg: empty for g.pkg itself, otherwise the import name,
// adding the import on the first reference to p.
func (g *gen) qualify(p *types.Package) string {
	if p == g.pkg {
		return ""
	}
	if name, ok := g.imports[p.Path()]; ok {
		return name
	}
	name := unique(p.Name(), g.taken)
	g.imports[p.Path()] = name
	return name
}

// paren wraps x in parentheses if it starts with a * dereference.
func paren(x string) string {
	if strings.HasPrefix(x, "*") {
		return "(" + x + ")"
	}
	return x
}
