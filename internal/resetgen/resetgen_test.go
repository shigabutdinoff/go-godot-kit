const srcA = `package a

import "time"

// generate:reset
type ResetableStruct struct {
	i     int
	str   string
	strP  *string
	s     []int
	m     map[string]string
	child *ResetableStruct
	at    time.Time
	arr   [2]int
	in    Inner
	pp    **int
	f     func()
	ok    bool
}

// Inner is a nested struct with its own Reset.
type Inner struct{ n int }

func (in *Inner) Reset() { in.n = 0 }

// not marked, so no Reset is needed
type skipped struct{ n int }
`

const testA = `package a

import (
	"testing"
	"time"
)

func TestReset(t *testing.T) {
	t.Parallel()
	str, n := "x", 7
	np := &n
	child := &ResetableStruct{i: 5}
	rs := &ResetableStruct{i: 1, str: "a", strP: &str, s: []int{1, 2}, m: map[string]string{"k": "v"},
		child: child, at: time.Now(), arr: [2]int{1, 2}, in: Inner{3}, pp: &np, f: func() {}, ok: true}
	rs.Reset()
	for field, ok := range map[string]bool{
		"i": rs.i == 0, "str": rs.str == "", "*strP": str == "", "len(s)": len(rs.s) == 0, "cap(s) kept": cap(rs.s) == 2,
		"m": len(rs.m) == 0, "child.i": child.i == 0, "child kept": rs.child == child, "at": rs.at.IsZero(),
		"arr": rs.arr == [2]int{}, "in": rs.in.n == 0, "**pp": n == 0, "f": rs.f == nil, "ok": !rs.ok,
	} {
		if !ok {
			t.Errorf("%s not reset: %+v", field, rs)
		}
	}
	var nilRS *ResetableStruct
	nilRS.Reset()
	(&ResetableStruct{}).Reset() // leaves nil pointers inside alone
}
`

func module(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	files["go.mod"] = "module example.com/m\n\ngo 1.24\n"
	for name, src := range files {
		p := filepath.Join(dir, name)
		require.NoError(t, os.MkdirAll(filepath.Dir(p), 0o755))
		require.NoError(t, os.WriteFile(p, []byte(src), 0o644))
	}
	return dir
}

func TestRun(t *testing.T) {
	t.Parallel()
	dir := module(t, map[string]string{})
	write := func(name, src string) {
		require.NoError(t, os.MkdirAll(filepath.Join(dir, filepath.Dir(name)), 0o755))
		require.NoError(t, os.WriteFile(filepath.Join(dir, name), []byte(src), 0o644))
	}
	write("a/a.go", srcA)
	write("a/a_test.go", testA)
	write("b/b.go", "package b\n\ntype plain struct{ n int }\n")

	require.NoError(t, Run(t.Context(), dir))

	gen, err := os.ReadFile(filepath.Join(dir, "a", genFile))
	require.NoError(t, err)
	assert.Contains(t, string(gen), "// Code generated by go-godot-kit/cmd/reset; DO NOT EDIT.")
	assert.Contains(t, string(gen), "func (r *ResetableStruct) Reset()")
	assert.Contains(t, string(gen), `"time"`)
	assert.NotContains(t, string(gen), "skipped")
	assert.NoFileExists(t, filepath.Join(dir, "b", genFile), "no file is written without markers")

	cmd := exec.Command("go", "test", "./...")
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	require.NoError(t, err, "%s\n%s", out, gen)

	require.NoError(t, Run(t.Context(), dir), "rerun on top of reset.gen.go")
}

func TestRun_NestedMarked(t *testing.T) {
	t.Parallel()
	dir := module(t, map[string]string{"a/a.go": `package a

//generate:reset
type Inner struct{ s []int }

//generate:reset
type Outer struct {
	in Inner
	ip *Inner
	pp **Inner
}

//generate:reset
type Сетка struct{ n int }
`})
	require.NoError(t, Run(t.Context(), dir))
	first, err := os.ReadFile(filepath.Join(dir, "a", genFile))
	require.NoError(t, err)
	assert.Contains(t, string(first), "o.in.Reset()")
	assert.Contains(t, string(first), "o.ip.Reset()")
	assert.Contains(t, string(first), "(*o.pp).Reset()")
	assert.Contains(t, string(first), "func (с *Сетка) Reset()")

	cmd := exec.Command("go", "vet", "./...")
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	require.NoError(t, err, "%s\n%s", out, first)

	require.NoError(t, Run(t.Context(), dir))
	second, err := os.ReadFile(filepath.Join(dir, "a", genFile))
	require.NoError(t, err)
	assert.Equal(t, string(first), string(second), "rerun produces the same code")
}

func TestRun_Generic(t *testing.T) {
	t.Parallel()
	dir := module(t, map[string]string{"a/a.go": `package a

//generate:reset
type Box[T any] struct{ v T }

//generate:reset
type Bag[K comparable, V any] struct {
	v   V
	p   *V
	s   []V
	m   map[K]V
	n   int
	box Box[V]
}
`, "a/a_test.go": `package a

import "testing"

func TestReset(t *testing.T) {
	t.Parallel()
	x := "x"
	b := &Bag[int, string]{v: "a", p: &x, s: []string{"a"}, m: map[int]string{1: "a"}, n: 1, box: Box[string]{"b"}}
	b.Reset()
	for field, ok := range map[string]bool{
		"v": b.v == "", "*p": x == "", "s": len(b.s) == 0, "m": len(b.m) == 0, "n": b.n == 0, "box": b.box.v == "",
	} {
		if !ok {
			t.Errorf("%s not reset: %+v", field, b)
		}
	}
}
`})
	require.NoError(t, Run(t.Context(), dir))
	gen, err := os.ReadFile(filepath.Join(dir, "a", genFile))
	require.NoError(t, err)
	assert.Contains(t, string(gen), "func (b *Bag[K, V]) Reset()")
	assert.Contains(t, string(gen), "b.v = *new(V)")
	assert.Contains(t, string(gen), "b.box.Reset()")

	cmd := exec.Command("go", "test", "./...")
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	require.NoError(t, err, "%s\n%s", out, gen)
}

func TestRun_NameClashes(t *testing.T) {
	t.Parallel()
	dir := module(t, map[string]string{
		"b/b.go":  "package b\n\ntype Ext struct{ N int }\n",
		"p1/p.go": "package dup\n\ntype T struct{ N int }\n",
		"p2/p.go": "package dup\n\ntype T struct{ N int }\n",
		"a/a.go": `package a

import (
	"example.com/m/b"
	d1 "example.com/m/p1"
	d2 "example.com/m/p2"
)

func dup() {}

// generate:reset
type Box struct {
	ext b.Ext
	t1  d1.T
	t2  d2.T
}
`})
	require.NoError(t, Run(t.Context(), dir))
	gen, err := os.ReadFile(filepath.Join(dir, "a", genFile))
	require.NoError(t, err)
	assert.Contains(t, string(gen), "func (b2 *Box) Reset()")
	assert.Contains(t, string(gen), `dup2 "example.com/m/p1"`)
	assert.Contains(t, string(gen), `dup3 "example.com/m/p2"`)

	cmd := exec.Command("go", "vet", "./...")
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	require.NoError(t, err, "%s\n%s", out, gen)
}

func TestRun_RemovesStale(t *testing.T) {
	t.Parallel()
	dir := module(t, map[string]string{
		"a/a.go":       "package a\n\n// generate:reset\ntype S struct{ n int }\n",
		"b/b.go":       "package b\n",
		"b/" + genFile: "// hand-written\npackage b\n",
	})
	require.NoError(t, Run(t.Context(), dir))
	require.FileExists(t, filepath.Join(dir, "a", genFile))

	unmarked := []byte("package a\n\ntype S struct{ n int }\n")
	require.NoError(t, os.WriteFile(filepath.Join(dir, "a", "a.go"), unmarked, 0o644))
	require.NoError(t, Run(t.Context(), dir))
	assert.NoFileExists(t, filepath.Join(dir, "a", genFile))
	assert.FileExists(t, filepath.Join(dir, "b", genFile), "a foreign file is not removed")
}

func TestRun_Cancelled(t *testing.T) {
	t.Parallel()
	dir := module(t, map[string]string{"a/a.go": "package a\n\n// generate:reset\ntype S struct{ n int }\n"})
	ctx, cancel := context.WithCancel(t.Context())
	cancel()
	require.Error(t, Run(ctx, dir))
	assert.NoFileExists(t, filepath.Join(dir, "a", genFile))
}

func TestRun_Errors(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name string
		src  string
		want string
	}{
		{"syntax error", "package a\n\nfunc {\n", ""},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			dir := module(t, map[string]string{"a.go": tt.src})
			err := Run(t.Context(), dir)
			require.Error(t, err)
			assert.ErrorContains(t, err, tt.want)
		})
	}
}
